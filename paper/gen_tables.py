def complexity(macros):
    rows = read_csv(RES / "config-complexity.csv")
    by = {r["design"]: r for r in rows}
    body = [r"\begin{table}[t]",
            r"\centering",
            r"\caption{Configuration complexity per design, counted from the device "
            r"configuration files (comments and mode-change wrappers excluded).}",
            r"\label{tab:complexity}",
            r"\footnotesize",
            r"\begin{tabular}{@{}lrrrr@{}}",
            r"\toprule",
            r"Design & Devices & Config lines & ACEs & Sec.\ features \\",
            r"\midrule"]
    base = int(by["D0"]["config_lines"])
    for d in DESIGNS:
        r = by.get(d)
        if not r:
            continue
        lines = int(r["config_lines"])
        body.append(f"{d} {DESIGN_NAMES[d]} & {r['devices_configured']} & {lines} "
                    f"($\\times${lines / base:.2f}) & {r['aces']} & {r['security_features']} \\\\")
        m = MACRO_DESIGN[d]
        macros[f"cfgLines{m}"] = r["config_lines"]
        macros[f"aces{m}"] = r["aces"]
        macros[f"feat{m}"] = r["security_features"]
        macros[f"devs{m}"] = r["devices_configured"]
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    for a, b in zip(DESIGNS, DESIGNS[1:]):
        if a in by and b in by:
            macros[f"deltaLines{MACRO_DESIGN[b]}"] = str(int(by[b]["config_lines"]) - int(by[a]["config_lines"]))
            macros[f"deltaAces{MACRO_DESIGN[b]}"] = str(int(by[b]["aces"]) - int(by[a]["aces"]))
    if "D3" in by:
        macros["lineRatioDthree"] = f"{int(by['D3']['config_lines']) / base:.2f}"
        feats = [f.strip() for f in by["D3"]["feature_list"].split(";") if f.strip()]
        macros["featListDthree"] = tex(", ".join(feats))
    write("complexity.tex", "\n".join(body))


def acl_inventory(macros):
    """ACEs per ACL per design, using the same counting rule as tools/config_stats.py."""
    rows = []
    for d in DESIGNS:
        counts = OrderedDict()          # label -> number of ACEs
        std_devs = defaultdict(set)     # numbered standard ACL -> devices carrying it
        for dev in devices(d):
            current = None
            for ln in cfg_lines(d, dev):
                s = ln.strip()
                if not s or s.startswith("!"):
                    continue
                m = re.match(r"ip access-list extended (\S+)", s)
                if m:
                    current = f"{m.group(1)} ({dev})"
                    continue
                if not ln.startswith(" "):
                    current = None
                m_std = re.match(r"access-list (\d+) (permit|deny)\s", s)
                m_asa = re.match(r"access-list (\S+) extended (permit|deny)\s", s)
                if m_std:
                    label = f"ACL {m_std.group(1)}"
                    std_devs[label].add(dev)
                elif m_asa:
                    label = f"{m_asa.group(1)} ({dev})"
                elif current and ACE_RE.search(ln):
                    label = current
                else:
                    continue
                counts[label] = counts.get(label, 0) + 1
        parts = [(f"{l} ({len(std_devs[l])} dev.)" if l in std_devs else l, n) for l, n in counts.items()]
        total = sum(counts.values())
        m = MACRO_DESIGN[d]
        macros[f"aceAsa{m}"] = str(sum(n for l, n in counts.items() if "(ASA-SRV)" in l))
        macros[f"aceCore{m}"] = str(sum(n for l, n in counts.items() if "(CORE-MLS)" in l))
        macros[f"aceStd{m}"] = str(sum(n for l, n in counts.items() if l in std_devs))
        rows.append((d, parts, total))
        macros[f"aceTotal{MACRO_DESIGN[d]}"] = str(total)
    body = [r"\begin{table}[t]", r"\centering",
            r"\caption{Where the ACEs are: access-control entries per ACL and design "
            r"(standard ACL~1 selects NAT traffic on EDGE-RTR; standard ACL~10 restricts VTY access).}",
            r"\label{tab:aclinv}", r"\scriptsize",
            r"\begin{tabular}{@{}lp{0.70\columnwidth}r@{}}", r"\toprule",
            r"Design & ACL (device): ACEs & Total \\", r"\midrule"]
    for d, parts, total in rows:
        desc = "; ".join(f"{tex(l)}: {n}" for l, n in parts) or "--"
        body.append(f"{d} & {desc} & {total} \\\\")
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    write("acl_inventory.tex", "\n".join(body))


