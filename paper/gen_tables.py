def extended_rows():
    """Rows of results/extended-attacks.csv, plus expected-only rows for any missing (test, design)."""
    p = RES / "extended-attacks.csv"
    rows = read_csv(p) if p.exists() else []
    have = {(r["test_id"], r["design"]) for r in rows}
    for tid, (name, loc, exp) in EXTENDED_EXPECTED.items():
        for d in DESIGNS:
            if (tid, d) not in have:
                for t in (1, 2, 3):
                    rows.append({"test_id": tid, "test_name": name, "design": d, "location": loc,
                                 "trial": str(t), "expected": exp[d], "observed": "",
                                 "time_to_detect_s": "", "time_to_contain_s": "", "collateral_ok": ""})
    return rows


def attack_matrix(macros):
    core = read_csv(RES / "attack-matrix.csv")
    ext = extended_rows()
    rows = core + ext
    cells = defaultdict(list)
    names = OrderedDict()
    for r in rows:
        names.setdefault(r["test_id"], r["test_name"])
        cells[(r["test_id"], r["design"])].append(r)
    n_obs_total = sum(1 for r in rows if (r["observed"] or "").strip())
    status = status_of(n_obs_total, len(rows))
    macros["attackStatus"] = status_of(sum(1 for r in core if (r["observed"] or "").strip()), len(core))
    macros["extendedStatus"] = status_of(sum(1 for r in ext if (r["observed"] or "").strip()), len(ext))
    blocked = Counter()
    partial = Counter()
    succeeded = Counter()
    notes = set()
    out = [r"\begin{table}[t]", r"\centering",
           r"\caption{Attack outcome per design (majority vote over all locations "
           r"$\times$ trials; ties go to the worse outcome). "
           r"\oS{}~succeeded, \oP{}~partial, \oB{}~blocked; for Q1, \oB{} means the node was "
           r"detected and quarantined." + caption_note(status) + "}",
           r"\label{tab:attacks}", r"\footnotesize", r"\setlength{\tabcolsep}{4pt}",
           r"\begin{tabular}{@{}llcccc@{}}", r"\toprule",
           r"ID & Attack & D0 & D1 & D2 & D3 \\", r"\midrule"]
    for tid, name in names.items():
        if tid == "A8":
            out.append(r"\midrule")
        line = [tid, ATTACK_SHORT.get(tid, tex(name))]
        for d in DESIGNS:
            rs = cells.get((tid, d), [])
            if not rs:
                line.append("--")
                continue
            obs = [norm_outcome(r["observed"]) for r in rs if (r["observed"] or "").strip()]
            if obs:
                o, k = majority(obs)
                mark = ""
                if k != len(obs):
                    mark += f"$^{{{k}/{len(obs)}}}$"
                    notes.add("kn")
                if len(obs) < len(rs):
                    mark += r"$^\ddagger$"
                    notes.add("dd")
            else:
                o, _ = majority([norm_outcome(r["expected"]) for r in rs])
                mark = r"$^\dagger$" if status == "partial" else ""
            if tid in EXTENDED_EXPECTED:
                macros[f"out{ {'A8': 'Aeight', 'Q1': 'Qone'}[tid] }{MACRO_DESIGN[d]}"] = o
            else:
                {"B": blocked, "P": partial, "S": succeeded}[o][d] += 1
            line.append(OUTCOME_TEX[o] + mark)
        out.append(" & ".join(line) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    foot = []
    if "kn" in notes:
        foot.append(r"Superscript $k/n$: only $k$ of the $n$ observed runs agreed with the majority.")
    if "dd" in notes:
        foot.append(r"$^\ddagger$: majority over the runs observed so far; the remaining runs are not yet measured.")
    if foot:
        out.append(r"\par\vspace{2pt}\parbox{\columnwidth}{\scriptsize " + " ".join(foot) + "}")
    out += [r"\end{table}", ""]
    write("attack_matrix.tex", "\n".join(out))
    for d in DESIGNS:
        m = MACRO_DESIGN[d]
        macros[f"blocked{m}"] = str(blocked[d])
        macros[f"partial{m}"] = str(partial[d])
        macros[f"succeeded{m}"] = str(succeeded[d])
    macros["nAttacks"] = str(len([n for n in names if n not in EXTENDED_EXPECTED]))
    macros["nAttackRows"] = str(len(core))
    # Q1 timing (measured only)
    q = [r for r in ext if r["test_id"] == "Q1" and (r.get("time_to_contain_s") or "").strip()]
    if q:
        tc = [float(r["time_to_contain_s"]) for r in q]
        td = [float(r["time_to_detect_s"]) for r in q if (r.get("time_to_detect_s") or "").strip()]
        macros["qOneContain"] = f"{statistics.fmean(tc):.1f}"
        macros["qOneDetect"] = f"{statistics.fmean(td):.1f}" if td else "--"
        macros["haveQone"] = "true"
    else:
        macros["haveQone"] = "false"


def _mean_sd(xs):
    if not xs:
        return None, None
    m = statistics.fmean(xs)
    sd = statistics.stdev(xs) if len(xs) > 1 else 0.0
    return m, sd


def attack_surface(macros):
    rows = read_csv(RES / "attack-surface.csv")
    hosts_n = 23
    svc_n = 10
    for k in rows[0].keys():
        m = re.match(r"expected_hosts_of_(\d+)", k)
        if m:
            hosts_n = int(m.group(1))
        m = re.match(r"expected_services_of_(\d+)", k)
        if m:
            svc_n = int(m.group(1))
    hk_e, hk_o = f"expected_hosts_of_{hosts_n}", f"observed_hosts_of_{hosts_n}"
    sk_e, sk_o = f"expected_services_of_{svc_n}", f"observed_services_of_{svc_n}"
    n_obs = sum(1 for r in rows if num(r[hk_o]) is not None)
    status = status_of(n_obs, len(rows))
    macros["surfaceStatus"] = status
    macros["nHosts"] = str(hosts_n)
    macros["nServices"] = str(svc_n)
    locs = list(OrderedDict.fromkeys(r["location"] for r in rows))
    loc_short = {l: l.split("-")[0] for l in locs}

    surf_notes = set()

    out = [r"\begin{table}[t]", r"\centering",
           rf"\caption{{Attack surface reachable from the compromised node: hosts answering "
           rf"(of {hosts_n}) and services accepting a connection (of {svc_n}); per-location means "
           rf"and overall mean$\pm$sd over {len(locs)} locations $\times$ trials." + caption_note(status) + "}",
           r"\label{tab:surface}", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
           r"\begin{tabular}{@{}l" + "r" * len(locs) + r"rrrr@{}}", r"\toprule",
           r"& \multicolumn{" + str(len(locs) + 2) + r"}{c}{Hosts reachable} & \multicolumn{2}{c}{Services} \\",
           r"\cmidrule(lr){2-" + str(len(locs) + 3) + r"}\cmidrule(l){" + str(len(locs) + 4) + "-" + str(len(locs) + 5) + "}",
           "Design & " + " & ".join(tex(loc_short[l]) for l in locs) + r" & mean$\pm$sd & \% & mean$\pm$sd & \% \\",
           r"\midrule"]
    for d in DESIGNS:
        rs = [r for r in rows if r["design"] == d]
        if not rs:
            continue
        # Never mix observed and expected values in one mean: if a design has any
        # observed runs, use only those (marked double-dagger if incomplete);
        # otherwise use the expected values (marked dagger when other designs are measured).
        observed_rs = [r for r in rs if num(r[hk_o]) is not None]
        if observed_rs:
            src, hk, sk = observed_rs, hk_o, sk_o
            dag = r"$^\ddagger$" if len(observed_rs) < len(rs) else ""
            if dag:
                surf_notes.add("dd")
        else:
            src, hk, sk = rs, hk_e, sk_e
            dag = r"$^\dagger$" if status == "partial" else ""
        cells = []
        for l in locs:
            xs = [num(r[hk]) for r in src if r["location"] == l and num(r[hk]) is not None]
            m, _ = _mean_sd(xs)
            cells.append("--" if m is None else f"{m:.1f}".rstrip("0").rstrip("."))
        hm, hs = _mean_sd([num(r[hk]) for r in src if num(r[hk]) is not None])
        sm, ss = _mean_sd([num(r[sk]) for r in src if num(r[sk]) is not None])
        if sm is None:
            sm, ss = 0.0, 0.0
        out.append(f"{d} {DESIGN_NAMES[d]} & " + " & ".join(cells) +
                   f" & {hm:.2f}$\\pm${hs:.2f}{dag} & {100 * hm / hosts_n:.0f} & "
                   f"{sm:.2f}$\\pm${ss:.2f}{dag} & {100 * sm / svc_n:.0f} \\\\")
        m = MACRO_DESIGN[d]
        macros[f"hostsPct{m}"] = f"{100 * hm / hosts_n:.0f}"
        macros[f"svcPct{m}"] = f"{100 * sm / svc_n:.0f}"
        macros[f"hostsMean{m}"] = f"{hm:.1f}"
        macros[f"svcMean{m}"] = f"{sm:.1f}"
    out += [r"\bottomrule", r"\end{tabular}", r"\par\vspace{2pt}\parbox{\columnwidth}{\scriptsize " +
            "; ".join(f"{tex(loc_short[l])} = {tex(l)}" for l in locs) +
            r". sd is the sample standard deviation over all runs of a design, so it mixes "
            r"location and trial variation." +
            (r" $^\ddagger$: mean over the runs observed so far only." if "dd" in surf_notes else "") +
            "}", r"\end{table}", ""]
    write("attack_surface.tex", "\n".join(out))


