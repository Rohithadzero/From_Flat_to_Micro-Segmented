def _short_reason(reason, limit=150):
    """Pick the deciding rule out of an analyser reason string."""
    m = re.search(r"BYPASS:[^;|]*", reason)
    parts = []
    if m:
        parts.append(m.group(0).strip())
    for m in re.finditer(r"(PERMIT|ACL_DENY|VTY_ACCEPT)[^;|\]]*", reason):
        frag = re.sub(r"\s*\(configs/[^)]*\)", "", m.group(0)).strip()
        if frag not in parts:
            parts.append(frag)
        if len("; ".join(parts)) > limit:
            break
    s = "; ".join(parts) or reason
    return s if len(s) <= limit else s[:limit - 3].rstrip() + "..."


def _static_attack_table(rows, macros, name):
    """results/static-analysis.csv with columns design,location,test_id,predicted,expected[,reason]."""
    # the authoritative expectation is results/attack-matrix.csv (it may have been corrected
    # after the analyser last ran); fall back to the analyser file's own 'expected' column
    exp_map = {}
    for r in read_csv(RES / "attack-matrix.csv"):
        exp_map.setdefault((r["design"], r["location"], r["test_id"]), []).append(norm_outcome(r["expected"]))
    rows = [dict(r, expected=majority(exp_map[(r["design"], r["location"], r["test_id"])])[0])
            if (r["design"], r["location"], r["test_id"]) in exp_map else r for r in rows]
    cells = defaultdict(list)
    for r in rows:
        cells[(r["test_id"], r["design"])].append(r)
    tests = list(OrderedDict.fromkeys(r["test_id"] for r in rows))
    n_dis = 0
    blocked = Counter()
    out = [r"\begin{table}[t]", r"\centering",
           r"\caption{Static analysis: attack verdicts predicted from the configurations "
           r"(majority over locations). A star marks a verdict that differs from the "
           r"design-analysis expectation in Table~\ref{tab:attacks}; the expected value is in "
           r"parentheses. " + STATIC_NOTE + "}",
           r"\label{tab:static}", r"\footnotesize",
           r"\begin{tabular}{@{}llcccc@{}}", r"\toprule",
           r"ID & Attack & D0 & D1 & D2 & D3 \\", r"\midrule"]
    for t in tests:
        line = [t, ATTACK_SHORT.get(t, tex(t))]
        for d in DESIGNS:
            rs = cells.get((t, d), [])
            if not rs:
                line.append("--")
                continue
            p, _ = majority([norm_outcome(r["predicted"]) for r in rs])
            e, _ = majority([norm_outcome(r["expected"]) for r in rs]) if "expected" in rs[0] else (p, 0)
            blocked[d] += p == "B"
            line.append(OUTCOME_TEX[p] + ("" if p == e else rf"$^\star$\,({e})"))
        out.append(" & ".join(line) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    # per-run disagreements with the deciding rule
    dis = [r for r in rows if "expected" in r and norm_outcome(r["predicted"]) != norm_outcome(r["expected"])]
    n_dis = len(dis)
    if dis:
        out += [r"\par\vspace{3pt}", r"\scriptsize", r"\begin{tabular}{@{}p{0.30\columnwidth}p{0.66\columnwidth}@{}}",
                r"\toprule", r"Run (exp.$\rightarrow$pred.) & Deciding rule (from the analyser) \\", r"\midrule"]
        for r in dis:
            loc = r.get("location", "").split("-")[0]
            out.append(f"{r['design']} {tex(loc)} {r['test_id']} ({norm_outcome(r['expected'])}$\\rightarrow$"
                       f"{norm_outcome(r['predicted'])}) & {tex(_short_reason(r.get('reason', '')))} \\\\")
        out += [r"\bottomrule", r"\end{tabular}"]
    out += [r"\end{table}", ""]
    for d in DESIGNS:
        macros[f"staticBlocked{MACRO_DESIGN[d]}"] = str(blocked[d])
    macros["staticDisagreements"] = str(n_dis)
    macros["staticRuns"] = str(len(rows))
    return out


def _static_surface_table(macros):
    p = RES / "static-surface.csv"
    if not p.exists():
        return []
    rows = read_csv(p)
    hk = next((k for k in rows[0] if re.fullmatch(r"hosts_reachable_of_\d+", k)), None)
    sk = next((k for k in rows[0] if re.fullmatch(r"services_reachable_of_\d+", k)), None)
    hl = next((k for k in rows[0] if k.startswith("hosts_at_listed_addr")), None)
    sl = next((k for k in rows[0] if k.startswith("services_at_listed_addr")), None)
    if not (hk and sk):
        return []
    out = [r"\begin{table}[t]", r"\centering",
           r"\caption{Static analysis: hosts and services reachable from the compromised node, "
           r"mean over locations. ``Any address'' also counts a device reached through any of its "
           r"interface addresses; ``listed'' counts only the addresses in the test plan. " + STATIC_NOTE + "}",
           r"\label{tab:staticsurface}", r"\footnotesize",
           r"\begin{tabular}{@{}lcccc@{}}", r"\toprule",
           r"& \multicolumn{2}{c}{Hosts} & \multicolumn{2}{c}{Services} \\",
           r"\cmidrule(lr){2-3}\cmidrule(l){4-5}",
           r"Design & any addr. & listed & any addr. & listed \\", r"\midrule"]
    for d in DESIGNS:
        rs = [r for r in rows if r["design"] == d]
        if not rs:
            continue
        f = lambda k: statistics.fmean(float(r[k]) for r in rs) if k else float("nan")
        h, s = f(hk), f(sk)
        hl_v, sl_v = (f(hl) if hl else h), (f(sl) if sl else s)
        fmt = lambda v: f"{v:.1f}".rstrip("0").rstrip(".")
        out.append(f"{d} {DESIGN_NAMES[d]} & {fmt(h)} & {fmt(hl_v)} & {fmt(s)} & {fmt(sl_v)} \\\\")
        m = MACRO_DESIGN[d]
        macros[f"staticHosts{m}"] = fmt(h)
        macros[f"staticSvc{m}"] = fmt(s)
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return out


