def vlan_plan(macros):
    vlans = OrderedDict()          # id -> {"name", "designs", "subnet", "gw"}
    for d in DESIGNS:
        for dev in devices(d):
            lines = cfg_lines(d, dev)
            for i, ln in enumerate(lines):
                m = re.match(r"^vlan (\d+)$", ln.strip())
                if m and not ln.startswith(" "):
                    vid = int(m.group(1))
                    name = ""
                    if i + 1 < len(lines) and lines[i + 1].strip().startswith("name "):
                        name = lines[i + 1].strip()[5:]
                    v = vlans.setdefault(vid, {"name": name, "designs": set(), "subnet": {}, "gw": {}})
                    v["name"] = v["name"] or name
