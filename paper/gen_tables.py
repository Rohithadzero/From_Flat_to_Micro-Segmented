"""Generate the LaTeX tables for the IEEE paper from the project data.

Reads (read-only):
  results/config-complexity.csv   measured config lines / ACEs / features
  results/attack-matrix.csv       7 attacks x 4 designs x locations x trials
  results/attack-surface.csv      hosts (of 23) / services (of 10) reachable
  results/functional.csv          9 legitimate flows x 4 designs
  results/static-analysis*.csv    optional, from a policy-analysis tool
  configs/<design>/*.txt          VLANs, addressing, ACL lines
  configs/END-DEVICES.md          server addresses

Writes paper/tables/*.tex. Re-run whenever the CSVs or configs change.

Honesty rule: wherever an `observed` column is empty the table falls back to
the `expected` (design-analysis) value and says so in the caption with
\\textit{(expected, not yet measured)}. Partially filled data is marked per
cell with a dagger. Expected values are never presented as measured.

Usage:  python paper/gen_tables.py
"""
import csv
import glob
import ipaddress
import re
import statistics
from collections import Counter, OrderedDict, defaultdict
from pathlib import Path

PAPER = Path(__file__).resolve().parent
ROOT = PAPER.parent
RES = ROOT / "results"
CFG = ROOT / "configs"
OUT = PAPER / "tables"

DESIGNS = ["D0", "D1", "D2", "D3"]
DESIGN_DIRS = {"D0": "D0-flat", "D1": "D1-vlan", "D2": "D2-zone-acl", "D3": "D3-microseg"}
DESIGN_NAMES = {"D0": "Flat", "D1": "VLAN-only", "D2": "Zone ACL", "D3": "Micro-seg"}
MACRO_DESIGN = {"D0": "Dzero", "D1": "Done", "D2": "Dtwo", "D3": "Dthree"}
OUTCOME_ORDER = ["S", "P", "B"]          # tie-break: the worse outcome for the defender wins
OUTCOME_TEX = {"S": r"\oS", "P": r"\oP", "B": r"\oB"}
EXPECTED_NOTE = r"\textit{(expected, not yet measured)}"
PARTIAL_NOTE = (r"\textit{Cells marked $^\dagger$ show expected values (not yet measured); "
                r"all other cells are measured.}")

HEADER = "% AUTO-GENERATED by paper/gen_tables.py -- do not edit by hand; edit the data and re-run.\n"


# ---------------------------------------------------------------- helpers
def tex(s):
    """Escape a plain string for LaTeX text mode."""
    s = str(s)
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
           "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    s = "".join(rep.get(c, c) for c in s)
    s = s.replace("->", r"$\rightarrow$").replace("<", r"\textless{}").replace(">", r"\textgreater{}")
    s = re.sub(r'"([^"]*)"', r"``\1''", s).replace('"', "''")
    return s


def read_csv(path):
    with open(path, encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


def write(name, body):
    OUT.mkdir(exist_ok=True)
    (OUT / name).write_text(HEADER + body, encoding="utf-8")
    print(f"  wrote tables/{name}")


def norm_outcome(v):
    v = (v or "").strip().upper()
    if not v:
        return ""
    if v[0] in "SPB":
        return v[0]
    raise ValueError(f"unknown attack outcome {v!r} (expected S/P/B)")


def norm_pass(v):
    v = (v or "").strip().upper()
    if not v:
        return ""
    if v.startswith("P"):
        return "PASS"
    if v.startswith("F"):
        return "FAIL"
    raise ValueError(f"unknown functional result {v!r} (expected PASS/FAIL)")


def num(v):
    v = (v or "").strip()
    return float(v) if v else None


def majority(values):
    """Majority vote over S/P/B; ties go to the outcome worse for the defender."""
    c = Counter(values)
    best = max(c.values())
    for o in OUTCOME_ORDER:
        if c.get(o) == best:
            return o, best
    raise AssertionError


def status_of(n_obs, n_total):
    if n_obs == 0:
        return "expected"
    if n_obs == n_total:
        return "measured"
    return "partial"


def caption_note(status):
    return {"expected": " " + EXPECTED_NOTE, "partial": " " + PARTIAL_NOTE, "measured": ""}[status]


def cfg_text(design, device):
    p = CFG / DESIGN_DIRS[design] / f"{device}.txt"
    return p.read_text(encoding="utf-8") if p.exists() else ""


def cfg_lines(design, device):
    return [ln.rstrip() for ln in cfg_text(design, device).splitlines()]


def devices(design):
    return sorted(p.stem for p in (CFG / DESIGN_DIRS[design]).glob("*.txt"))


def interface_blocks(lines):
    """Yield (interface_name, [sub-lines]) for every 'interface X' block."""
    cur, body = None, []
    for ln in lines:
        if ln.startswith("interface "):
            if cur:
                yield cur, body
            cur, body = ln[len("interface "):].strip(), []
        elif cur and ln.startswith(" "):
            body.append(ln.strip())
        elif cur:
            yield cur, body
            cur, body = None, []
    if cur:
        yield cur, body


def named_acl(lines, name):
    out, on = [], False
    for ln in lines:
        if ln.startswith("ip access-list extended "):
            on = ln.split()[-1] == name
            if on:
                out.append(ln)
            continue
        if on:
            if ln.startswith(" "):
                out.append(ln)
            else:
                break
    return out


ACE_RE = re.compile(r"^\s*(permit|deny)\s|^access-list \d+ (permit|deny)\s|^access-list \S+ extended (permit|deny)\s")


