def functional(macros):
    rows = read_csv(RES / "functional.csv")
    n_obs = sum(1 for r in rows if (r["observed"] or "").strip())
    status = status_of(n_obs, len(rows))
    macros["functionalStatus"] = status
    tests = OrderedDict()
    for r in rows:
        tests.setdefault(r["test_id"], {})[r["design"]] = r
    passed = Counter()
    total = Counter()
    out = [r"\begin{table}[t]", r"\centering",
           r"\caption{Functional preservation: legitimate flows that must keep working in every "
           r"design (\cmark~pass, \xmark~fail)." + caption_note(status) + "}",
           r"\label{tab:functional}", r"\footnotesize", r"\setlength{\tabcolsep}{4pt}",
           r"\begin{tabular}{@{}llcccc@{}}", r"\toprule",
           r"ID & Legitimate flow & D0 & D1 & D2 & D3 \\", r"\midrule"]
    for tid, per in tests.items():
        name = next(iter(per.values()))["test_name"]
        line = [tid, FUNC_SHORT.get(tid, tex(name))]
        for d in DESIGNS:
            r = per.get(d)
            if not r:
                line.append("--")
                continue
            o = norm_pass(r["observed"])
            mark = ""
            if not o:
                o = norm_pass(r["expected"])
                if status == "partial":
                    mark = r"$^\dagger$"
            total[d] += 1
            passed[d] += o == "PASS"
            line.append((r"\cmark" if o == "PASS" else r"\xmark") + mark)
        out.append(" & ".join(line) + r" \\")
    out.append(r"\midrule")
    out.append(r"\multicolumn{2}{@{}l}{Pass rate} & " +
               " & ".join(f"{passed[d]}/{total[d]}" for d in DESIGNS) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    write("functional.tex", "\n".join(out))
    for d in DESIGNS:
        macros[f"funcPass{MACRO_DESIGN[d]}"] = f"{passed[d]}/{total[d]}"
    macros["nFunctional"] = str(len(tests))


